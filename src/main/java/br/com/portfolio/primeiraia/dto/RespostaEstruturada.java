
package br.com.portfolio.primeiraia.dto;

public class RespostaEstruturada {

    private String conceito;
    private String explicacao;
    private String exemploJava;

    public RespostaEstruturada() {
    }

    public String getConceito() {
        return conceito;
    }

    public void setConceito(String conceito) {
        this.conceito = conceito;
    }

    public String getExplicacao() {
        return explicacao;
    }

    public void setExplicacao(String explicacao) {
        this.explicacao = explicacao;
    }

    public String getExemploJava() {
        return exemploJava;
    }

    public void setExemploJava(String exemploJava) {
        this.exemploJava = exemploJava;
    }
}


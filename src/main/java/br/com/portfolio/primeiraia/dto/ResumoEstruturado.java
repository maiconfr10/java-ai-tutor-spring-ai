package br.com.portfolio.primeiraia.dto;

public class ResumoEstruturado {
	
	private String titulo;
	private String resumo;
	private String pontoPrincipal;
	
	 public ResumoEstruturado() {
	    }

	 public String getTitulo() {
		 return titulo;
	 }

	 public void setTitulo(String titulo) {
		 this.titulo = titulo;
	 }

	 public String getResumo() {
		 return resumo;
	 }

	 public void setResumo(String resumo) {
		 this.resumo = resumo;
	 }

	 public String getPontoPrincipal() {
		 return pontoPrincipal;
	 }

	 public void setPontoPrincipal(String pontoPrincipal) {
		 this.pontoPrincipal = pontoPrincipal;
	 }
	 
	 


}
